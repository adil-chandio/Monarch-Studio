def brand_mark(d: ImageDraw.ImageDraw):
    """Persistent corner mark — same place in every video (brand law)."""
    f_small = font("black", 20)
    f_ep = font("med", 18)
    x, y = 64, 58
    draw_tracked(d, (x, y), "MONARCH", f_small, WHITE, tracking=3)
    xe = x + tracked_w(d, "MONARCH", f_small, 3) + 14
    draw_tracked(d, (xe, y), "FILES", f_small, AMBER, tracking=3)
    d.text((x, y + 30), "EP 01", font=f_ep, fill=(255, 255, 255, 165))


def render_overlay(spec: dict, path: pathlib.Path) -> bool:
    if spec.get("kind") == "none":
        img = Image.new("RGBA", (W, H), (0, 0, 0, 0))
        d = ImageDraw.Draw(img)
        brand_mark(d)
        img.save(path)
        return True

    img = Image.new("RGBA", (W, H), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    kind = spec["kind"]

    if kind in ("big", "line"):
        text = spec["main"]
        size = {"big": 132, "line": 62}[kind]
        f = font("black", size)
        tracking = 4 if kind == "big" else 1
        while tracked_w(d, text, f, tracking) > W - 220 and size > 34:
            size -= 4
            f = font("black", size)
        tw = tracked_w(d, text, f, tracking)
        x = (W - tw) // 2
        y = {"center": H // 2 - size // 2, "lower": H - 300}.get(spec.get("pos", "lower"), H - 260)
        glow = Image.new("RGBA", (W, H), (0, 0, 0, 0))
        gd = ImageDraw.Draw(glow)
        draw_tracked(gd, (x, y), text, f, (0, 0, 0, 255), tracking)
        glow = glow.filter(ImageFilter.GaussianBlur(26))
        img.alpha_composite(glow)
        shadowed(d, (x, y), text, f, WHITE, tracking)
        if kind == "big":
            d.rectangle([x - 2, y + size + 34, x + min(tw, 150), y + size + 40], fill=AMBER)

    elif kind == "split":
        for i, (label, value) in enumerate([spec["left"], spec["right"]]):
            cx = W // 4 + i * (W // 2)
            fl, fv = font("black", 30), font("black", 96)
            lw, vw = tracked_w(d, label, fl, 6), tracked_w(d, value, fv, 2)
            base = H - 380
            d.text((cx - lw // 2, base), label, font=fl, fill=AMBER)
            x = cx - vw // 2
            glow = Image.new("RGBA", (W, H), (0, 0, 0, 0))
            draw_tracked(ImageDraw.Draw(glow), (x, base + 54), value, fv, (0, 0, 0, 255), 2)
            img.alpha_composite(glow.filter(ImageFilter.GaussianBlur(22)))
            shadowed(d, (x, base + 54), value, fv, WHITE, 2)
        d.rectangle([W // 2 - 1, H - 400, W // 2 + 1, H - 190], fill=(255, 255, 255, 70))

    elif kind == "stat":
        fnum = font("black", 176)
        fnote = font("black", 40)
        accent = spec.get("accent", False)
        num, note = spec["num"], spec["note"]
        while tracked_w(d, num, fnum, 4) > W - 320 and fnum.size > 60:
            fnum = font("black", fnum.size - 6)
        nw = tracked_w(d, num, fnum, 4)
