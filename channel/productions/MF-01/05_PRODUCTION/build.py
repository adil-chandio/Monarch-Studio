_font_cache: dict[tuple[str, int], ImageFont.FreeTypeFont] = {}


def font(style: str, size: int) -> ImageFont.FreeTypeFont:
    key = (style, size)
    if key in _font_cache:
        return _font_cache[key]
    path = FONTS / ("Caveat-VF.ttf" if style == "hand" else "Montserrat-VF.ttf")
    f = ImageFont.truetype(str(path), size)
    if style != "hand":
        want = {"black": 900, "bold": 700, "semi": 600, "med": 500, "reg": 400}.get(style, 700)
        try:
            f.set_variation_by_axes([want])
        except Exception:
            pass
    _font_cache[key] = f
    return f


def text_w(d: ImageDraw.ImageDraw, s: str, f: ImageFont.FreeTypeFont) -> int:
    return int(d.textlength(s, font=f))


def draw_tracked(d, xy, s, f, fill, tracking=0, anchor_left=True):
    """Letter-spaced text (PIL has no tracking)."""
    x, y = xy
    for ch in s:
        d.text((x, y), ch, font=f, fill=fill)
        x += d.textlength(ch, font=f) + tracking
    return x


def tracked_w(d, s, f, tracking=0) -> int:
    return int(sum(d.textlength(c, font=f) for c in s) + tracking * max(0, len(s) - 1))


def shadowed(d, xy, s, f, fill, tracking=0, shadow=(0, 0, 0, 210), off=4):
    x, y = xy
    draw_tracked(d, (x + off, y + off), s, f, shadow, tracking)
    draw_tracked(d, (x, y), s, f, fill, tracking)


