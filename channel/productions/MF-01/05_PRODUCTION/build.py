SR = 48000


def wav_write(path: pathlib.Path, data: np.ndarray):
    """data: float32 (n, 2) in -1..1"""
    d = np.clip(data, -1.0, 1.0)
    pcm = (d * 32767.0).astype("<i2")
    with wave.open(str(path), "wb") as w:
        w.setnchannels(2)
        w.setsampwidth(2)
        w.setframerate(SR)
        w.writeframes(pcm.tobytes())


def wav_read(path: pathlib.Path) -> np.ndarray:
    with wave.open(str(path), "rb") as w:
        n, sw, ch = w.getnframes(), w.getsampwidth(), w.getnchannels()
        raw = w.readframes(n)
    a = np.frombuffer(raw, dtype="<i2").astype(np.float32) / 32768.0
    return a.reshape(-1, ch) if ch > 1 else a.reshape(-1, 1)


def build_score(total_s: float, cues: list[float]) -> np.ndarray:
    """Low sub drone + breath + impact hits at chapter turns. All synthesised."""
    n = int(total_s * SR)
    t = np.arange(n, dtype=np.float32) / SR
    out = np.zeros(n, dtype=np.float32)

    # sub drone — two detuned low sines with slow swell
    swell = 0.55 + 0.45 * np.sin(2 * np.pi * 0.023 * t - 1.2)
    out += 0.20 * np.sin(2 * np.pi * 43.65 * t) * swell
    out += 0.13 * np.sin(2 * np.pi * 65.41 * t + 0.7) * swell
    out += 0.07 * np.sin(2 * np.pi * 87.31 * t + 1.9) * (0.4 + 0.6 * swell)

    # air — slow filtered noise, very low
    rng = np.random.default_rng(7)
    air = rng.standard_normal(n).astype(np.float32)
    k = int(SR * 0.35)
    kern = np.hanning(k).astype(np.float32)
    kern /= kern.sum()
    air = np.convolve(air, kern, mode="same")
    out += 0.055 * air * (0.5 + 0.5 * np.sin(2 * np.pi * 0.017 * t))

    # impacts — low thump with exponential decay at each cue
    for c in cues:
        i0 = int(c * SR)
        if i0 >= n:
            continue
        ln = min(int(0.9 * SR), n - i0)
        tt = np.arange(ln, dtype=np.float32) / SR
        env = np.exp(-tt * 7.5).astype(np.float32)
        freq = 62.0 * np.exp(-tt * 5.0) + 34.0
        thump = np.sin(2 * np.pi * freq * tt) * env
        out[i0:i0 + ln] += 0.30 * thump

    # gentle limiter
    out = np.tanh(out * 1.15) * 0.85
    return np.stack([out, out * 0.97], axis=1).astype(np.float32)


def build_voice_track() -> pathlib.Path:
    """Concat the five VO chunks with breathing room between them."""
    sil = OUT / "sil.wav"
    run([FFMPEG, "-y", "-hide_banner", "-loglevel", "error", "-f", "lavfi",
         "-i", "anullsrc=r=48000:cl=stereo", "-t", "0.5", str(sil)], "silence")

    parts = []
    for i in range(1, 6):
        src = VOICE / f"vo_0{i}.mp3"
        if not src.exists():
            print(f"  ✗ missing VO {src}", file=sys.stderr)
            raise SystemExit(1)
        dst = OUT / f"vo_{i:02d}.wav"
        run([FFMPEG, "-y", "-hide_banner", "-loglevel", "error", "-i", str(src),
             "-ar", "48000", "-ac", "2", str(dst)], f"vo {i}")
        parts += [dst, sil]
    parts = parts[:-1]

    lst = OUT / "vo_concat.txt"
    lst.write_text("".join(f"file '{p.as_posix()}'\n" for p in parts))
    voice = OUT / "voice.wav"
    run([FFMPEG, "-y", "-hide_banner", "-loglevel", "error",
         "-f", "concat", "-safe", "0", "-i", str(lst), str(voice)], "voice concat")
    return voice


def mix(voice: pathlib.Path, score: np.ndarray) -> pathlib.Path:
    score_p = OUT / "score.wav"
    wav_write(score_p, score)

    vo = wav_read(voice)
    dev = abs(len(vo) - len(score)) / SR
    print(f"  VO {len(vo)/SR:.2f}s · score {len(score)/SR:.2f}s · drift {dev:.2f}s")
    if dev > 1.5:
        print("  ! timing drift over 1.5s — check shot durations", file=sys.stderr)

    # pass 1 — duck the score under the voice, then sum
    raw = OUT / "master_raw.wav"
    run([FFMPEG, "-y", "-hide_banner", "-loglevel", "error",
         "-i", str(voice), "-i", str(score_p),
         "-filter_complex",
         "[1:a]volume=0.34[bedx];"
         "[bedx][0:a]sidechaincompress=threshold=0.035:ratio=9:attack=12:release=420:makeup=1[duck];"
         "[0:a][duck]amix=inputs=2:duration=first:normalize=0,"
         "alimiter=limit=0.94,aresample=48000[a]",
         "-map", "[a]", "-c:a", "pcm_s16le", str(raw)], "mix pass 1")

    # pass 2 — EBU R128 delivery loudness (−16 LUFS, per the editor doctrine)
    master = OUT / "master.wav"
    run([FFMPEG, "-y", "-hide_banner", "-loglevel", "error",
         "-i", str(raw), "-af", "loudnorm=I=-16:TP=-1.5:LRA=9",
         "-c:a", "pcm_s16le", str(master)], "mix pass 2 (loudnorm)")
    return master


def mux(picture: pathlib.Path, master: pathlib.Path) -> pathlib.Path:
    final = ROOT.parent.parent.parent.parent / "channel" / "productions" / "MF-01" / "05_PRODUCTION" / "MONARCH_FILES_01.mp4"
    run([FFMPEG, "-y", "-hide_banner", "-loglevel", "error",
         "-i", str(picture), "-i", str(master),
         "-c:v", "copy", "-c:a", "aac", "-b:a", "256k",
         "-movflags", "+faststart", "-shortest", str(final)], "mux")
    return final


def measure(path: pathlib.Path) -> dict:
    p = run([FFMPEG, "-i", str(path), "-f", "null", "-"], "measure")
    loud = subprocess.run(
        [FFMPEG, "-hide_banner", "-nostats", "-i", str(path), "-af", "loudnorm=print_format=json",
         "-f", "null", "-"], capture_output=True, text=True)
    j = loud.stderr[loud.stderr.rfind("{"):loud.stderr.rfind("}") + 1]
    try:
        d = json.loads(j)
    except Exception:
        d = {}
    return {
        "i_lufs": d.get("input_i"), "lra": d.get("input_lra"),
        "true_peak": d.get("input_tp"),
    }


def main():
    print(f"MONARCH FILES #01 — build   ({len(SHOTS)} shots, {TOTAL:.1f}s planned)\n")

    print("[1/5] voice track")
    voice = build_voice_track()

    print("[2/5] score")
    cues = []
    acc = 0.0
    for sid, _, _, dur, _ in SHOTS:
        if sid in (1, 4, 7, 13, 14, 15, 16, 17, 19, 20, 22, 23, 24):
            cues.append(acc)
        acc += dur
    score = build_score(max(TOTAL, len(wav_read(voice)) / SR), cues)

    print("[3/5] picture")
    segs = build_segments()
    picture = concat_segments(segs)

    print("[4/5] mix")
    master = mix(voice, score)

    print("[5/5] mux")
    final = mux(picture, master)

    m = measure(final)
