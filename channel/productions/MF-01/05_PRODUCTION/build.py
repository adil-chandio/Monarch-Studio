def run(cmd: list[str], label: str):
    p = subprocess.run(cmd, capture_output=True, text=True)
    if p.returncode != 0:
        print(f"  ✗ {label}\n{p.stderr[-2500:]}", file=sys.stderr)
        raise SystemExit(1)
    return p


def build_segments() -> list[pathlib.Path]:
    segs: list[pathlib.Path] = []
    for i, (sid, plate, spec, dur, motion) in enumerate(SHOTS, 1):
        plate_p = PLATES / f"{plate}.jpg"
        if not plate_p.exists():
            print(f"  ✗ missing plate {plate_p}", file=sys.stderr)
            raise SystemExit(1)
        ov_p = ROOT / "overlays" / f"ov_{sid:02d}.png"
        render_overlay(spec, ov_p)

        frames = int(dur * FPS)
        m = MOTION[motion].format(n=max(frames - 1, 1))
        seg = OUT / f"seg_{sid:02d}.mp4"
        if seg.exists() and seg.stat().st_size > 100_000:
            print(f"  · shot {sid:02d}  cached")
            segs.append(seg)
            continue
        cmd = [
            FFMPEG, "-y", "-hide_banner", "-loglevel", "error",
            "-loop", "1", "-t", f"{dur}", "-i", str(plate_p),
            "-loop", "1", "-t", f"{dur}", "-i", str(ov_p),
            "-filter_complex",
            f"[0:v]scale=3840:2160:force_original_aspect_ratio=increase,"
            f"crop=3840:2160,zoompan={m}:d=1:s={W}x{H}:fps={FPS}[bg];"
            f"[bg]{GRADE}[graded];"
            f"[graded][1:v]overlay=0:0:format=auto,format=yuv420p[v]",
            "-map", "[v]", "-r", str(FPS), "-c:v", "libx264",
            "-preset", "medium", "-crf", "19", "-pix_fmt", "yuv420p",
            str(seg),
        ]
        run(cmd, f"segment {sid}")
        segs.append(seg)
        print(f"  ✓ shot {sid:02d}  {plate:18s} {dur:5.1f}s  {motion}")
    return segs


def concat_segments(segs: list[pathlib.Path]) -> pathlib.Path:
    lst = OUT / "concat.txt"
    lst.write_text("".join(f"file '{s.as_posix()}'\n" for s in segs))
    video = OUT / "picture.mp4"
    run([FFMPEG, "-y", "-hide_banner", "-loglevel", "error",
         "-f", "concat", "-safe", "0", "-i", str(lst),
         "-c", "copy", str(video)], "concat")
    return video


