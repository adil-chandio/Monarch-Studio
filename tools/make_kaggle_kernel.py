#!/usr/bin/env python3
"""make_kaggle_kernel — ek chunk ke liye Kaggle kernel package banata hai (API push ke liye).

Kaggle par "New Notebook" dabane ki zarurat khatam: GitHub Action khud kernel push karta hai.
Is script ka output do files hain: `main.ipynb` + `kernel-metadata.json`.

  python3 tools/make_kaggle_kernel.py --user myname --slug monarch-stick-1 --only k01,k02,k03 --out /tmp/k1
"""

from __future__ import annotations

import argparse
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
BRANCH = "arena/3d8cfad7-monarch-studio"
REPO = "https://github.com/adil-chandio/Monarch-Studio"


def slugify(text: str) -> str:
    slug = re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")
    return slug[:50]


def notebook(only: str, branch: str) -> dict:
    src = '''# Kaggle kernel — Monarch film chunk (auto-generated by tools/make_kaggle_kernel.py)
# Har GPU par alag worker (Kaggle par T4 x2 milta hai) taake waqt aadha lage.
import json, os, pathlib, shutil, subprocess, sys

BRANCH = "__BRANCH__"
REPO = "__REPO__"
ONLY = "__ONLY__"

repo = pathlib.Path("/kaggle/working/repo")
if not (repo / "tools/kaggle_stick_film.py").exists():
    subprocess.run(["git", "clone", "--depth", "1", "-b", BRANCH, REPO, str(repo)], check=True)

subprocess.run([sys.executable, "-m", "pip", "install", "-q", "diffusers>=0.32",
                "transformers>=4.49", "accelerate", "ftfy", "sentencepiece", "safetensors",
                "regex", "imageio-ffmpeg"], check=False)
print("deps installed", flush=True)

scenes = [s for s in ONLY.split(",") if s.strip()]
try:
    import torch
    n_gpu = torch.cuda.device_count()
    for i in range(n_gpu):
        print("GPU", i, torch.cuda.get_device_name(i), flush=True)
except Exception as exc:
    print("torch check fail:", exc, flush=True)
    n_gpu = 1

groups = [scenes]
if n_gpu >= 2 and len(scenes) > 1:
    half = (len(scenes) + 1) // 2
    groups = [scenes[:half], scenes[half:]]
    print("parallel workers:", groups, flush=True)

procs = []
for i, group in enumerate(groups):
    out = f"/kaggle/working/stick-w{i}"
    cmd = [sys.executable, str(repo / "tools/kaggle_stick_film.py"),
           "--out", out, "--no-kit", "--only", ",".join(group)]
    env = dict(os.environ)
    if len(groups) > 1:
        env["CUDA_VISIBLE_DEVICES"] = str(i)
    print("$", " ".join(cmd), "| CUDA_VISIBLE_DEVICES=" + env.get("CUDA_VISIBLE_DEVICES", "all"), flush=True)
    procs.append(subprocess.Popen(cmd, env=env))

codes = [p.wait() for p in procs]
print("worker exit codes:", codes, flush=True)

clips = pathlib.Path("/kaggle/working/clips"); clips.mkdir(exist_ok=True)
for i in range(len(groups)):
    for f in pathlib.Path(f"/kaggle/working/stick-w{i}").glob("*.mp4"):
        if f.stat().st_size > 20000:
            shutil.copy2(f, clips / f.name)
got = sorted(p.name for p in clips.glob("*.mp4"))
print("CLIPS:", got, flush=True)
print(json.dumps({"only": ONLY, "clips": got, "exit": codes}))
'''
    src = (src.replace("__BRANCH__", branch).replace("__REPO__", REPO)
             .replace("__ONLY__", only))
    return {
        "cells": [{"cell_type": "code", "execution_count": None, "metadata": {},
                   "outputs": [], "source": src.splitlines(True)}],
        "metadata": {"kernelspec": {"display_name": "Python 3", "name": "python3"},
                     "language_info": {"name": "python"}},
        "nbformat": 4, "nbformat_minor": 5,
    }


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(prog="make_kaggle_kernel")
    ap.add_argument("--user", required=True, help="Kaggle username")
    ap.add_argument("--slug", required=True)
    ap.add_argument("--only", required=True, help="k01,k02,k03")
    ap.add_argument("--out", required=True)
    ap.add_argument("--branch", default=BRANCH)
    ap.add_argument("--title", default="")
    args = ap.parse_args(argv)

    out = pathlib.Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    slug = slugify(args.slug)
    scenes = ",".join(s.strip() for s in args.only.split(",") if s.strip())

    (out / "main.ipynb").write_text(json.dumps(notebook(scenes, args.branch), indent=1) + "\n")
    meta = {
        "id": f"{args.user}/{slug}",
        # Kaggle niyam: title ka slug hi kernel id ka slug hona chahiye, warna 409 Conflict.
        "title": args.title or slug,
        "code_file": "main.ipynb",
        "language": "python",
        "kernel_type": "notebook",
        "is_private": True,
        "enable_gpu": True,
        "enable_internet": True,
        "dataset_sources": [],
        "competition_sources": [],
        "kernel_sources": [],
        "model_sources": [],
    }
    (out / "kernel-metadata.json").write_text(json.dumps(meta, indent=1) + "\n")
    print(f"kernel ready: {meta['id']} ({scenes}) -> {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
