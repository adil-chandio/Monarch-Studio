#!/usr/bin/env python3
"""Fail-closed visual/technical gate for a future Chaos Video 1 3D release.

v2's 21 automated encoding/edit gates all passed while the user still observed
jelly facial movement. Those gates are historical technical evidence, not a
substitute for likeness/motion review. This new gate requires a real 3D asset
*and* a version-matched explicit user review; it never manufactures approval.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

REQUIRED_REVIEW = (
    "locked_face_likeness", "hair_and_charcoal_blazer_black_open_collar_shirt",
    "natural_head_body_hand_motion", "no_jelly_or_flat_image_cards",
    "reference_beat_fidelity", "crown_above_monarch_studio", "cinematic_visual_quality",
)


def hash_file(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def count_mesh(path: Path) -> tuple[int,int,float]:
    verts=[]
    faces=0
    for l in path.read_text().splitlines():
        if l.startswith('v '):
            verts.append([float(x) for x in l.split()[1:4]])
        elif l.startswith('f '):
            faces+=1
    return len(verts),faces,(max(v[1] for v in verts)-min(v[1] for v in verts)) if verts else 0.


def check(model: Path, review: Path | None) -> dict:
    checks={}
    manifest_path=model/'model_manifest.json'
    face=model/'monarch_face_v5.obj'
    texture=model/'monarch_face_v5_albedo.png'
    checks['model_manifest_present']=manifest_path.is_file()
    checks['head_is_3d_geometry']=False
    checks['static_fitted_geometry_hash']=False
    checks['separate_3d_wardrobe_and_hair']=all((model/f'{name}.obj').is_file()
                                             for name in ('coat','shirt','lapels','hair_front','hair_back','skin'))
    checks['surface_albedo_asset_present']=texture.is_file()
    manifest={}
    if checks['model_manifest_present']:
        try:
            manifest=json.loads(manifest_path.read_text())
        except (json.JSONDecodeError,UnicodeDecodeError):
            checks['model_manifest_present']=False
    if face.is_file():
        try:
            vertices,faces,depth=count_mesh(face)
            checks['head_is_3d_geometry']=vertices>=468 and faces>=898 and depth>.065
            checks['static_fitted_geometry_hash']=(hash_file(face)==manifest.get('mesh_sha256')
                                                   and manifest.get('vertices')==vertices
                                                   and manifest.get('triangles')==faces)
        except (ValueError,UnicodeDecodeError):
            pass
    checks['explicit_user_review_current_mesh']=False
    review_details=None
    if review and review.is_file() and checks['static_fitted_geometry_hash']:
        try:
            review_details=json.loads(review.read_text())
            checks['explicit_user_review_current_mesh']=(
                review_details.get('approved_by_user') is True
                and review_details.get('face_mesh_sha256')==manifest['mesh_sha256']
                and all(review_details.get(k) is True for k in REQUIRED_REVIEW)
            )
        except (json.JSONDecodeError,UnicodeDecodeError):
            pass
    return {
        'status':'PASS' if all(checks.values()) else 'BLOCKED',
        'checks':checks,
        'review_missing':[k for k in REQUIRED_REVIEW if not review_details or review_details.get(k) is not True],
        'message':'Cannot mark a 3D master final until an actual visual approval for THIS mesh exists.'
        if not all(checks.values()) else 'Technical mesh and explicit visual review verified.',
    }


def main() -> None:
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--model-dir',required=True,type=Path)
    parser.add_argument('--review',type=Path,help='Explicit user visual review JSON; never generated by this tool')
    args=parser.parse_args()
    result=check(args.model_dir,args.review)
    print(json.dumps(result,indent=2))
    raise SystemExit(0 if result['status']=='PASS' else 1)


if __name__=='__main__':main()
